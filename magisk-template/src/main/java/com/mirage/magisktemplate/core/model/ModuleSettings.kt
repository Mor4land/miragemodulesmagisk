package com.mirage.magisktemplate.core.model

data class ModuleSettings(
    val featureEnabled: Boolean = true,
    val boostMode: String = "balanced", // "powersave", "balanced", "performance", "extreme"
    val animationScale: Float = 1.0f,
    val verboseLogs: Boolean = false,
    val aggressiveDoze: Boolean = false,
    val touchSamplingRate: Int = 240, // 120, 240, 360, 480
    val customArgs: String = ""
) {
    /**
     * Serializes settings into POSIX shell script key-value declarations
     * for easy sourcing inside service.sh or action.sh (`. $MODPATH/config.sh`)
     */
    fun toShellScript(): String {
        return buildString {
            appendLine("#!/system/bin/sh")
            appendLine("# Auto-generated by Magisk Template Companion App")
            appendLine("# Module: ${ModuleConfig.MODULE_ID}")
            appendLine()
            appendLine("FEATURE_ENABLED=${if (featureEnabled) "1" else "0"}")
            appendLine("BOOST_MODE=\"$boostMode\"")
            appendLine("ANIMATION_SCALE=$animationScale")
            appendLine("VERBOSE_LOGS=${if (verboseLogs) "1" else "0"}")
            appendLine("AGGRESSIVE_DOZE=${if (aggressiveDoze) "1" else "0"}")
            appendLine("TOUCH_SAMPLING_RATE=$touchSamplingRate")
            appendLine("CUSTOM_ARGS=\"${customArgs.replace("\"", "\\\"")}\"")
        }
    }

    companion object {
        fun fromShellScript(content: String): ModuleSettings {
            var feature = true
            var mode = "balanced"
            var anim = 1.0f
            var verbose = false
            var doze = false
            var touch = 240
            var args = ""

            content.lines().forEach { rawLine ->
                val line = rawLine.trim()
                if (line.isEmpty() || line.startsWith("#")) return@forEach
                val eqIdx = line.indexOf('=')
                if (eqIdx == -1) return@forEach
                val key = line.substring(0, eqIdx).trim()
                val value = line.substring(eqIdx + 1).trim().removeSurrounding("\"").removeSurrounding("'")

                when (key) {
                    "FEATURE_ENABLED" -> feature = value == "1" || value.equals("true", ignoreCase = true)
                    "BOOST_MODE" -> mode = value
                    "ANIMATION_SCALE" -> anim = value.toFloatOrNull() ?: 1.0f
                    "VERBOSE_LOGS" -> verbose = value == "1" || value.equals("true", ignoreCase = true)
                    "AGGRESSIVE_DOZE" -> doze = value == "1" || value.equals("true", ignoreCase = true)
                    "TOUCH_SAMPLING_RATE" -> touch = value.toIntOrNull() ?: 240
                    "CUSTOM_ARGS" -> args = value
                }
            }

            return ModuleSettings(
                featureEnabled = feature,
                boostMode = mode,
                animationScale = anim,
                verboseLogs = verbose,
                aggressiveDoze = doze,
                touchSamplingRate = touch,
                customArgs = args
            )
        }
    }
}
